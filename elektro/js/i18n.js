function vwBase() {
  const path = location.pathname.replace(/\/+$/, "");
  return /\/elektro$/.test(path) ? "./" : "../";
}

function vwApplyI18n(lang) {
  const pack = VW_I18N[lang] || VW_I18N.de;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (pack[key] != null) el.textContent = pack[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (pack[key] != null) el.setAttribute("placeholder", pack[key]);
  });
  document.querySelectorAll(".lang button").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
  });
  try {
    localStorage.setItem("vw-lang", lang);
  } catch (_) {}
}

function vwInitLang() {
  let lang = "de";
  try {
    const saved = localStorage.getItem("vw-lang");
    if (saved && VW_I18N[saved]) lang = saved;
  } catch (_) {}
  vwApplyI18n(lang);
  document.querySelectorAll(".lang button").forEach((btn) => {
    btn.addEventListener("click", () => vwApplyI18n(btn.dataset.lang));
  });
}

function vwInitNav() {
  const toggle = document.querySelector(".nav-toggle");
  if (!toggle) return;
  toggle.addEventListener("click", () => {
    document.body.classList.toggle("nav-open");
  });
  document.querySelectorAll(".nav-main a").forEach((a) => {
    a.addEventListener("click", () => document.body.classList.remove("nav-open"));
  });
}

function vwInitReveal() {
  const nodes = document.querySelectorAll(".reveal");
  if (!nodes.length) return;
  if (!("IntersectionObserver" in window)) {
    nodes.forEach((n) => n.classList.add("is-in"));
    return;
  }
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((e) => {
        if (e.isIntersecting) {
          e.target.classList.add("is-in");
          io.unobserve(e.target);
        }
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -8% 0px" }
  );
  nodes.forEach((n) => io.observe(n));
}

function vwInitContactForm() {
  const form = document.querySelector("#project-form");
  if (!form) return;
  form.addEventListener("submit", (e) => {
    e.preventDefault();
    const fd = new FormData(form);
    const topic = fd.get("topic") || "";
    const body = [
      `Name: ${fd.get("name") || ""}`,
      `Company: ${fd.get("company") || ""}`,
      `Email: ${fd.get("email") || ""}`,
      `Topic: ${topic}`,
      "",
      fd.get("message") || "",
    ].join("\n");
    const subject = encodeURIComponent(`Voltwerk · ${topic || "Projektanfrage"}`);
    location.href = `mailto:hello@thedesigns.org?subject=${subject}&body=${encodeURIComponent(body)}`;
  });
}

